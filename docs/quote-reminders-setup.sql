begin;
create table if not exists public.quote_reminder_subscriptions (
  id bigint generated by default as identity primary key,
  browser_hash text not null unique check (browser_hash ~ '^[a-f0-9]{64}$'),
  endpoint_hash text not null unique check (endpoint_hash ~ '^[a-f0-9]{64}$'),
  endpoint text,
  p256dh text,
  auth text,
  vapid_public_key text not null,
  enabled boolean not null default true,
  last_attempt_date date,
  last_sent_date date,
  claim_token uuid,
  failure_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (not enabled or (endpoint is not null and p256dh is not null and auth is not null)),
  check (endpoint is null or char_length(endpoint) between 10 and 2048)
);
create index if not exists quote_reminder_pending_idx on public.quote_reminder_subscriptions(vapid_public_key, last_attempt_date, id) where enabled;

create table if not exists public.quote_reminder_limits (
  kind text not null,
  client_hash text not null check (client_hash ~ '^[a-f0-9]{64}$'),
  window_start timestamptz not null,
  attempts integer not null,
  primary key(kind, client_hash, window_start)
);
alter table public.quote_reminder_subscriptions enable row level security;
alter table public.quote_reminder_limits enable row level security;
revoke all on public.quote_reminder_subscriptions, public.quote_reminder_limits from public, anon, authenticated;
revoke all on sequence public.quote_reminder_subscriptions_id_seq from public, anon, authenticated;
grant all on public.quote_reminder_subscriptions, public.quote_reminder_limits to service_role;
grant all on sequence public.quote_reminder_subscriptions_id_seq to service_role;

create or replace function public.limit_quote_requests(p_browser_hash text, p_network_hash text, p_action text)
returns void language plpgsql security definer set search_path = '' as $$
declare bucket timestamptz := pg_catalog.date_trunc('hour', pg_catalog.clock_timestamp()); n integer;
begin
  if p_browser_hash !~ '^[a-f0-9]{64}$' or p_network_hash !~ '^[a-f0-9]{64}$' or p_action not in ('subscribe','disable','test') then raise exception 'Invalid request' using errcode='22023'; end if;
  delete from public.quote_reminder_limits where window_start < bucket - interval '1 day';
  insert into public.quote_reminder_limits values ('network',p_network_hash,bucket,1)
    on conflict(kind,client_hash,window_start) do update set attempts=public.quote_reminder_limits.attempts+1 returning attempts into n;
  if n>60 then raise exception 'Please wait' using errcode='PT429'; end if;
  insert into public.quote_reminder_limits values (p_action,p_browser_hash,bucket,1)
    on conflict(kind,client_hash,window_start) do update set attempts=public.quote_reminder_limits.attempts+1 returning attempts into n;
  if n>10 then raise exception 'Please wait' using errcode='PT429'; end if;
end; $$;

create or replace function public.save_quote_subscription(p_browser_hash text, p_endpoint_hash text, p_endpoint text, p_p256dh text, p_auth text, p_vapid_public_key text)
returns void language plpgsql security definer set search_path = '' as $$
declare existing public.quote_reminder_subscriptions%rowtype; own_id bigint;
begin
  if p_browser_hash is null or p_browser_hash !~ '^[a-f0-9]{64}$' or p_endpoint_hash is null or p_endpoint_hash !~ '^[a-f0-9]{64}$'
    or p_endpoint is null or char_length(p_endpoint) not between 10 and 2048
    or p_p256dh is null or p_p256dh !~ '^[A-Za-z0-9_-]{87}$'
    or p_auth is null or p_auth !~ '^[A-Za-z0-9_-]{22}$'
    or p_vapid_public_key is null or p_vapid_public_key !~ '^[A-Za-z0-9_-]{87}$'
    then raise exception 'Invalid subscription' using errcode='22023'; end if;
  -- Serialize the short enrollment operation; daily delivery uses row-level claims.
  perform pg_catalog.pg_advisory_xact_lock(91573421);
  select * into existing from public.quote_reminder_subscriptions where endpoint_hash=p_endpoint_hash for update;
  select id into own_id from public.quote_reminder_subscriptions where browser_hash=p_browser_hash;
  if existing.id is not null then
    if existing.enabled and existing.browser_hash<>p_browser_hash and (existing.p256dh<>p_p256dh or existing.auth<>p_auth) then raise exception 'Subscription ownership mismatch' using errcode='42501'; end if;
    if own_id is not null and own_id<>existing.id then delete from public.quote_reminder_subscriptions where id=own_id; end if;
    update public.quote_reminder_subscriptions set browser_hash=p_browser_hash,endpoint=p_endpoint,p256dh=p_p256dh,auth=p_auth,vapid_public_key=p_vapid_public_key,enabled=true,claim_token=null,updated_at=pg_catalog.now() where id=existing.id;
  elsif own_id is not null then
    update public.quote_reminder_subscriptions set endpoint_hash=p_endpoint_hash,endpoint=p_endpoint,p256dh=p_p256dh,auth=p_auth,vapid_public_key=p_vapid_public_key,enabled=true,claim_token=null,updated_at=pg_catalog.now() where id=own_id;
  else
    insert into public.quote_reminder_subscriptions(browser_hash,endpoint_hash,endpoint,p256dh,auth,vapid_public_key) values (p_browser_hash,p_endpoint_hash,p_endpoint,p_p256dh,p_auth,p_vapid_public_key);
  end if;
end; $$;

create or replace function public.disable_quote_subscription(p_browser_hash text, p_endpoint_hash text default null, p_p256dh text default null, p_auth text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  update public.quote_reminder_subscriptions set enabled=false,endpoint=null,p256dh=null,auth=null,claim_token=null,updated_at=pg_catalog.now()
  where browser_hash=p_browser_hash or (endpoint_hash=p_endpoint_hash and p256dh=p_p256dh and auth=p_auth);
end; $$;

create or replace function public.claim_quote_deliveries(p_day date, p_vapid_public_key text, p_limit integer default 12)
returns table(id bigint, endpoint text, p256dh text, auth text, claim_token uuid)
language plpgsql security definer set search_path = '' as $$
begin
  if p_day is null or p_day<>(pg_catalog.now() at time zone 'UTC')::date or p_limit not between 1 and 100 then raise exception 'Invalid delivery request' using errcode='22023'; end if;
  delete from public.quote_reminder_subscriptions s where not s.enabled and s.updated_at<pg_catalog.now()-interval '30 days';
  return query with candidates as (
    select s.id from public.quote_reminder_subscriptions s
    where s.enabled and s.vapid_public_key=p_vapid_public_key and (s.last_attempt_date is null or s.last_attempt_date<p_day)
    order by s.id limit p_limit for update skip locked
  ) update public.quote_reminder_subscriptions s set last_attempt_date=p_day,claim_token=pg_catalog.gen_random_uuid()
    from candidates c where s.id=c.id returning s.id,s.endpoint,s.p256dh,s.auth,s.claim_token;
end; $$;

create or replace function public.finish_quote_deliveries(p_results jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare item jsonb;
begin
  if pg_catalog.jsonb_typeof(p_results)<>'array' or pg_catalog.jsonb_array_length(p_results)>100 then raise exception 'Invalid results' using errcode='22023'; end if;
  for item in select * from pg_catalog.jsonb_array_elements(p_results) loop
    if item->>'status' not in ('sent','expired','failed') then raise exception 'Invalid result' using errcode='22023'; end if;
    update public.quote_reminder_subscriptions s set
      last_sent_date=case when item->>'status'='sent' then s.last_attempt_date else s.last_sent_date end,
      failure_count=case when item->>'status'='sent' then 0 else s.failure_count+1 end,
      enabled=case when item->>'status'='expired' then false else s.enabled end,
      endpoint=case when item->>'status'='expired' then null else s.endpoint end,
      p256dh=case when item->>'status'='expired' then null else s.p256dh end,
      auth=case when item->>'status'='expired' then null else s.auth end,
      claim_token=null
      where s.id=(item->>'id')::bigint and s.claim_token=(item->>'claim_token')::uuid;
  end loop;
end; $$;

revoke all on function public.limit_quote_requests(text,text,text), public.save_quote_subscription(text,text,text,text,text,text), public.disable_quote_subscription(text,text,text,text), public.claim_quote_deliveries(date,text,integer), public.finish_quote_deliveries(jsonb) from public,anon,authenticated;
grant execute on function public.limit_quote_requests(text,text,text), public.save_quote_subscription(text,text,text,text,text,text), public.disable_quote_subscription(text,text,text,text), public.claim_quote_deliveries(date,text,integer), public.finish_quote_deliveries(jsonb) to service_role;
commit;
