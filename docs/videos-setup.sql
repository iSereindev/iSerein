-- Run once in the Supabase SQL Editor for the existing iSEREIN project.
-- This creates a new table; it does not change articles, quotes, or books.
begin;

create table public.videos (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 160),
  youtube_url text not null check (char_length(btrim(youtube_url)) between 1 and 2048),
  caption text check (char_length(caption) <= 1000),
  published_date date not null default ((now() at time zone 'UTC')::date),
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create index videos_publication_idx
  on public.videos (published_date desc, id desc)
  where active = true;

alter table public.videos enable row level security;

-- Explicit grants work on both older and newly provisioned Supabase projects.
revoke all on table public.videos from public, anon, authenticated;
grant select on table public.videos to anon, authenticated;
grant all on table public.videos to service_role;
revoke all on sequence public.videos_id_seq from public, anon, authenticated;
grant all on sequence public.videos_id_seq to service_role;

create policy "Visitors can read published videos"
  on public.videos
  for select
  to anon, authenticated
  using (active = true and published_date <= (now() at time zone 'UTC')::date);

commit;
