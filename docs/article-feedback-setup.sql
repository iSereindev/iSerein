begin;

create table if not exists public.article_feedback (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public.articles(id) on delete cascade,
  visitor_hash text not null check (visitor_hash ~ '^[a-f0-9]{64}$'),
  reaction text check (reaction in ('up', 'down')),
  comment text check (char_length(comment) between 1 and 1200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (article_id, visitor_hash),
  check (reaction is not null or comment is not null)
);

create table if not exists public.article_feedback_limits (
  kind text not null check (kind in ('network', 'reader')),
  client_hash text not null check (client_hash ~ '^[a-f0-9]{64}$'),
  window_start timestamptz not null,
  submissions integer not null,
  primary key (kind, client_hash, window_start)
);
create index if not exists article_feedback_limits_window_idx on public.article_feedback_limits(window_start);

alter table public.article_feedback enable row level security;
alter table public.article_feedback_limits enable row level security;
revoke all on public.article_feedback, public.article_feedback_limits from public, anon, authenticated;
revoke all on sequence public.article_feedback_id_seq from public, anon, authenticated;
grant all on public.article_feedback, public.article_feedback_limits to service_role;
grant all on sequence public.article_feedback_id_seq to service_role;

-- The server uses a secret key. Visitors cannot call this function directly.
create or replace function public.record_article_feedback(
  p_article_id bigint,
  p_visitor_hash text,
  p_request_hash text,
  p_reaction text default null,
  p_comment text default null
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  bucket timestamptz := pg_catalog.date_trunc('minute', pg_catalog.clock_timestamp());
  attempts integer;
begin
  if p_article_id is null or p_article_id < 1
     or p_visitor_hash is null or p_visitor_hash !~ '^[a-f0-9]{64}$'
     or p_request_hash is null or p_request_hash !~ '^[a-f0-9]{64}$'
     or (p_reaction is not null and p_reaction not in ('up', 'down'))
     or (p_comment is not null and (pg_catalog.char_length(pg_catalog.btrim(p_comment)) < 1 or pg_catalog.char_length(p_comment) > 1200))
     or (p_reaction is null and p_comment is null) then
    raise exception 'Invalid feedback' using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.articles
    where id = p_article_id and published_date <= (pg_catalog.now() at time zone 'UTC')::date
  ) then
    raise exception 'Reading unavailable' using errcode = 'P0002';
  end if;

  delete from public.article_feedback_limits where window_start < bucket - interval '10 minutes';
  insert into public.article_feedback_limits(kind, client_hash, window_start, submissions)
    values ('network', p_request_hash, bucket, 1)
    on conflict (kind, client_hash, window_start) do update
      set submissions = public.article_feedback_limits.submissions + 1
    returning submissions into attempts;
  if attempts > 120 then
    raise exception 'Please wait before sending more feedback' using errcode = 'PT429';
  end if;
  insert into public.article_feedback_limits(kind, client_hash, window_start, submissions)
    values ('reader', p_visitor_hash, bucket, 1)
    on conflict (kind, client_hash, window_start) do update
      set submissions = public.article_feedback_limits.submissions + 1
    returning submissions into attempts;
  if attempts > 15 then
    raise exception 'Please wait before sending more feedback' using errcode = 'PT429';
  end if;

  insert into public.article_feedback(article_id, visitor_hash, reaction, comment)
    values (p_article_id, p_visitor_hash, p_reaction, p_comment)
    on conflict (article_id, visitor_hash) do update
      set reaction = coalesce(excluded.reaction, public.article_feedback.reaction),
          comment = coalesce(excluded.comment, public.article_feedback.comment),
          updated_at = pg_catalog.now();
end;
$$;
revoke all on function public.record_article_feedback(bigint, text, text, text, text) from public, anon, authenticated;
grant execute on function public.record_article_feedback(bigint, text, text, text, text) to service_role;

-- Owner-only report. Percentages describe submitted reactions, not all readers.
create or replace view public.article_feedback_summary with (security_invoker = true) as
select a.id as article_id, a.title, a.topic,
  count(f.id) filter (where f.reaction = 'up') as thumbs_up,
  count(f.id) filter (where f.reaction = 'down') as thumbs_down,
  count(f.id) filter (where f.comment is not null) as comments,
  round(100.0 * count(f.id) filter (where f.reaction = 'up') / nullif(count(f.reaction), 0), 0) as positive_percent,
  max(f.updated_at) as last_feedback_at
from public.articles a
left join public.article_feedback f on f.article_id = a.id
where a.published_date <= (now() at time zone 'UTC')::date
group by a.id, a.title, a.topic;
revoke all on public.article_feedback_summary from public, anon, authenticated;
grant select on public.article_feedback_summary to service_role;

commit;
