-- Local sandbox catalogue only. Never apply this bootstrap to a live project.
create table public.articles (
  id bigint generated by default as identity primary key,
  title text not null, subtitle text, content text not null,
  topic text not null, reading_time integer default 3,
  published_date date not null, is_featured boolean not null default false
);
create table public.home_quotes (id bigint generated by default as identity primary key, sentence text not null, display_order integer default 0, active boolean default true);
create table public.books (id uuid primary key default gen_random_uuid(), title text, author text, edition text, topic text, description text, affiliate_url text, cover_url text, active boolean default true, display_order integer default 0, created_at timestamptz default now());
create table public.videos (id bigint generated by default as identity primary key, title text, caption text, youtube_url text, active boolean default true, published_date date);
alter table public.articles enable row level security;
alter table public.home_quotes enable row level security;
alter table public.books enable row level security;
alter table public.videos enable row level security;
create policy published on public.articles for select using (published_date <= (now() at time zone 'UTC')::date);
create policy active on public.home_quotes for select using (active);
create policy active on public.books for select using (active);
create policy published on public.videos for select using (active and published_date <= (now() at time zone 'UTC')::date);
grant select on public.articles, public.home_quotes, public.books, public.videos to anon, authenticated;
create function public.tomorrow_reading_titles() returns jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object('total',count(*),'titles',coalesce((select jsonb_agg(title) from
 (select title from public.articles where published_date=(now() at time zone 'UTC')::date+1 order by id desc limit 3) t),'[]'::jsonb))
 from public.articles where published_date=(now() at time zone 'UTC')::date+1;
$$;
